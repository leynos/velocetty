#!/usr/bin/env bun
/** @file Regenerates the Dafny artefacts and carries each source's module header into them. */
/*
 * `lsc gen` writes only a one-line provenance comment, so a generated module
 * said nothing about its purpose or its TypeScript source. This wrapper runs
 * the generator and then prepends a header derived from that source's own
 * `@file` summary, so the description lives beside the code it describes
 * rather than in a second copy that can drift.
 */
import {execFileSync} from 'node:child_process';
import {readFileSync, writeFileSync} from 'node:fs';
import path from 'node:path';

const repoRoot = path.resolve(import.meta.dir, '..');
const listPath = path.join(repoRoot, 'LemmaScript-files.txt');
const lscBinary = path.join(repoRoot, 'node_modules', '.bin', 'lsc');

/** The proof sources listed for verification, ignoring comments and timeouts. */
const readEntries = () =>
  readFileSync(listPath, 'utf8')
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line !== '' && !line.startsWith('#'))
    .map((line) => line.split(/\s+/)[0] ?? '');

/** The `@file` summary a TypeScript module already carries. */
const moduleSummary = (sourcePath) => {
  const source = readFileSync(path.join(repoRoot, sourcePath), 'utf8');
  const match = /@file\s+([^\n*]+)/.exec(source);
  return match?.[1]?.trim() ?? sourcePath;
};

/** The header prepended to one generated artefact. */
const headerFor = (sourcePath) =>
  [
    '// ---------------------------------------------------------------------------',
    `// ${moduleSummary(sourcePath)}`,
    `// Source: ${sourcePath.split(path.sep).join('/')}`,
    '// Generated by `lsc gen --backend=dafny`; do not edit. Run `make prove` to',
    '// regenerate this file and this header.',
    '// ---------------------------------------------------------------------------',
    ''
  ].join('\n');

execFileSync(lscBinary, ['gen', '--backend=dafny'], {cwd: repoRoot, stdio: 'inherit'});

// `lsc gen` rewrites every artefact from scratch, so the header is added after
// it runs rather than being preserved across generations.
for (const source of readEntries()) {
  const generated = path.join(repoRoot, source.replace(/\.ts$/, '.dfy.gen'));
  writeFileSync(generated, headerFor(source) + readFileSync(generated, 'utf8'), 'utf8');
}
