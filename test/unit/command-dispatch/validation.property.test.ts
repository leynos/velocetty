/**
 * @file Property test: no handler runs for arguments its schema rejects.
 *
 * `INV-VALIDATE-BEFORE-EXEC`. The schema space is infinite, so the invariant is
 * a relation rather than a table: for every generated schema and every value,
 * the handler runs exactly when a fresh Ajv instance with the same options
 * accepts the value. Ajv's own correctness is the stated axiom
 * (`AX-AJV`); its verdict is the oracle this property compares against.
 *
 * The property drives the real dispatcher and the real schema validator, so it
 * checks the shipped validation path rather than a model of it.
 *
 * Invariants:
 * - Both classes are generated by construction: at least one valid and one
 *   invalid value per run.
 * - The permanent mutant — one that skips validation for `null` — must fail the
 *   property, proving the property has teeth.
 *
 * Usage:
 * - `bun test --isolate test/unit/command-dispatch/validation.property.test.ts`
 *
 * Related modules:
 * - `../../../lib/command-dispatch/dispatcher.ts`
 * - `../../../lib/command-registry-validation.ts`
 */
import {expect, test} from 'bun:test';
import Ajv from 'ajv';
import fc from 'fast-check';

import {asCommandId} from '@shared/types/commands';
import type {JsonObject, JsonValue} from '@shared/types/json';
import {createCommandSchemaValidator} from '../../../lib/command-registry-validation';
import {createCommandDispatcher} from '../../../lib/command-dispatch/dispatcher';
import {createDispatcherFakes, fakeDefinition} from '../../testUtils/command-dispatcher-fakes';

const COMMAND = 'test:property:validation';
const RUNS = 200;
const TIMEOUT_MS = 30_000;

/** One declared property of a generated object schema. */
type FieldSpec =
  | {readonly kind: 'string'; readonly minLength: number}
  | {readonly kind: 'integer'; readonly minimum: number};

const fieldSpec: fc.Arbitrary<FieldSpec> = fc.oneof(
  fc.record({kind: fc.constant<'string'>('string'), minLength: fc.integer({min: 1, max: 4})}),
  fc.record({kind: fc.constant<'integer'>('integer'), minimum: fc.integer({min: -5, max: 5})})
);

const fieldList: fc.Arbitrary<FieldSpec[]> = fc.array(fieldSpec, {minLength: 1, maxLength: 3});

const propertyName = (index: number): string => `p${index}`;

/** Turns a field list into a closed object schema. */
const toJsonSchema = (fields: readonly FieldSpec[]): JsonObject => {
  const properties: Record<string, JsonValue> = {};
  fields.forEach((field, index) => {
    properties[propertyName(index)] =
      field.kind === 'string'
        ? {type: 'string', minLength: field.minLength}
        : {type: 'integer', minimum: field.minimum};
  });

  return {
    type: 'object',
    properties,
    required: fields.map((_field, index) => propertyName(index)),
    additionalProperties: false
  };
};

/** A value the schema must accept. */
const toValidValue = (fields: readonly FieldSpec[]): JsonObject =>
  Object.fromEntries(
    fields.map((field, index) => [
      propertyName(index),
      field.kind === 'string' ? 'x'.repeat(field.minLength) : field.minimum
    ])
  );

/** A value the schema must reject, built by breaking exactly one field. */
const toInvalidValue = (fields: readonly FieldSpec[], mutation: number): JsonValue => {
  const valid = toValidValue(fields);
  const target = propertyName(mutation % fields.length);

  if (mutation % 3 === 0) {
    const withoutTarget = {...valid};
    delete withoutTarget[target];
    return withoutTarget;
  }
  if (mutation % 3 === 1) {
    return {...valid, [target]: fields[mutation % fields.length]?.kind === 'string' ? 42 : 'not a number'};
  }
  return {...valid, unexpected: true};
};

/** A fresh Ajv with the same options as the validator under test. */
const oracleAccepts = (schema: JsonObject, value: JsonValue): boolean => {
  const ajv = new Ajv({allErrors: true});
  // SAFETY: Ajv's `validate` returns a boolean when called without a callback,
  // which is the documented signature this test relies on (axiom AX-AJV).
  return ajv.validate(schema, value) as boolean;
};

interface DispatchOutcome {
  readonly handlerRan: boolean;
  readonly result: {
    readonly status: string;
    readonly error?: {readonly code: string; readonly issues?: readonly unknown[]};
  };
}

/** Runs one invocation through the real dispatcher over the given validator. */
const dispatch = async (
  schema: JsonObject,
  value: JsonValue | undefined,
  validateArgs: (id: ReturnType<typeof asCommandId>, args: unknown) => {ok: boolean; error?: unknown}
): Promise<DispatchOutcome> => {
  const fakes = createDispatcherFakes<undefined>({
    commands: {[COMMAND]: {definition: fakeDefinition(COMMAND, {argsSchema: schema}), handlerValue: null}}
  });

  // Swap in the validator under test; everything else stays the real
  // interpreter and executor.
  const ports = {
    ...fakes.ports,
    catalogue: {
      ...fakes.ports.catalogue,
      // SAFETY: the fake ports only ever call this with a validated JSON payload, and the
      // validator under test answers for exactly that command id.
      validateArgs: ((id: ReturnType<typeof asCommandId>, args: JsonValue) => validateArgs(id, args)) as never
    }
  };

  const dispatcher = createCommandDispatcher(ports);
  const result = await dispatcher.invoke({id: asCommandId(COMMAND), args: value, source: 'ui'});

  return {
    handlerRan: fakes.handlerCalls.length > 0,
    result: result.status === 'error' ? {status: result.status, error: result.error} : {status: result.status}
  };
};

/** The real validator, over a definition table that answers for the generated command. */
const realValidator = (schema: JsonObject) => {
  const definition = fakeDefinition(COMMAND, {argsSchema: schema});
  const validator = createCommandSchemaValidator({getDefinition: () => definition});
  return (id: ReturnType<typeof asCommandId>, args: unknown) => validator.validateArgs(id, args);
};

test(
  'the handler runs exactly when a fresh Ajv accepts the arguments',
  async () => {
    let sawValid = false;
    let sawInvalid = false;

    await fc.assert(
      fc.asyncProperty(fieldList, fc.nat({max: 2}), async (fields, mutation) => {
        const schema = toJsonSchema(fields);
        const validateArgs = realValidator(schema);

        const valid = toValidValue(fields);
        const invalid = toInvalidValue(fields, mutation);

        // The generator's label is cross-checked against a fresh Ajv instance.
        expect(oracleAccepts(schema, valid)).toBe(true);
        expect(oracleAccepts(schema, invalid)).toBe(false);

        const validOutcome = await dispatch(schema, valid, validateArgs);
        const invalidOutcome = await dispatch(schema, invalid, validateArgs);

        if (validOutcome.handlerRan) {
          sawValid = true;
        }
        if (!invalidOutcome.handlerRan) {
          sawInvalid = true;
        }

        expect(validOutcome.handlerRan).toBe(true);
        expect(invalidOutcome.handlerRan).toBe(false);
        expect(invalidOutcome.result.error?.code).toBe('INVALID_COMMAND_ARGS');
        return true;
      }),
      {numRuns: RUNS}
    );

    // Non-vacuity: both classes were produced.
    expect(sawValid).toBe(true);
    expect(sawInvalid).toBe(true);
  },
  TIMEOUT_MS
);

test(
  'reports every Ajv issue, not just the first',
  async () => {
    await fc.assert(
      fc.asyncProperty(fieldList, async (fields) => {
        const schema = toJsonSchema(fields);
        const value: JsonObject = {...toValidValue(fields), unexpected: true};
        // Break every declared field as well, so several issues must be reported.
        for (const [index] of fields.entries()) {
          value[propertyName(index)] = 'not the declared type';
        }

        const outcome = await dispatch(schema, value, realValidator(schema));

        const ajv = new Ajv({allErrors: true});
        ajv.validate(schema, value);
        expect(outcome.result.error?.issues).toHaveLength(ajv.errors?.length ?? 0);
        return true;
      }),
      {numRuns: RUNS}
    );
  },
  TIMEOUT_MS
);

test(
  'a validation-skipping mutant is rejected by the same property',
  async () => {
    // The mutant returns "valid" for `null` without asking Ajv. Generated
    // schemas are non-nullable objects, so `null` must be refused.
    const skippingMutant = (schema: JsonObject) => {
      const real = realValidator(schema);
      return (id: ReturnType<typeof asCommandId>, args: unknown) =>
        args === null ? {ok: true, value: args} : real(id, args);
    };

    const mutantProperty = fc.asyncProperty(fieldList, async (fields) => {
      const schema = toJsonSchema(fields);
      const outcome = await dispatch(schema, null, skippingMutant(schema));
      return outcome.handlerRan === oracleAccepts(schema, null);
    });

    await expect(fc.assert(mutantProperty, {numRuns: 20})).rejects.toThrow();
  },
  TIMEOUT_MS
);
